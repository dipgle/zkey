"""Fault-only fixture. Corrupt config to exercise the real launcher warning;
repair ONLY by real clicks on the native settings screen, then type again.
"""
from pathlib import Path
import ctypes as C
import os
import subprocess
import sys
import time

ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'scripts'))
import editor_ui
from native_x11 import window_for_pid


def exercise(window,text,password,key,expect,pump,x,t,display,xid):
    config=Path(os.environ['ZKEY_NATIVE_CONFIG_PATH'])
    if not config.resolve().is_relative_to(ROOT/'.tmp'):raise RuntimeError('Fault fixture config outside scratch')
    # EXCEPTION: inject malformed bytes solely to exercise a failure. The valid
    # replacement below is generated by the real settings UI, never seeded.
    config.write_text('schema = broken\n')
    key('Tab')  # password -> normal field: real focus-in reload rejects config
    if not text.has_focus():raise AssertionError('Fault fixture did not return to typing entry')
    session=Path(os.environ['ZKEY_NATIVE_SESSION_ROOT'])
    deadline=time.monotonic()+6
    dialog_pid=None
    while time.monotonic()<deadline:
        children=Path(f'/proc/{os.getppid()}/task/{os.getppid()}/children').read_text().split()
        for pid in children:
            try:command=Path(f'/proc/{pid}/cmdline').read_bytes().split(b'\0')
            except FileNotFoundError:continue
            if b'--alert' in command:dialog_pid=int(pid);break
        if dialog_pid:break
        pump(.02)
    if dialog_pid is None:raise AssertionError('Alive-but-disabled native engine has no visible supervisor warning')
    Atspi,app=editor_ui.connect(dialog_pid)
    deadline=time.monotonic()+5
    while time.monotonic()<deadline:
        nodes=list(editor_ui.walk(app))
        labels=[n.get_name() or '' for n in nodes if n.get_role()==Atspi.Role.LABEL]
        close=next((n for n in nodes if n.get_role()==Atspi.Role.PUSH_BUTTON and n.get_name()=='Đóng'),None)
        if close and any('Telex đã tắt' in label for label in labels):break
        pump(.03)
    else:raise AssertionError('Actual runtime failure warning has no readable recovery instruction')
    t.XTestFakeMotionEvent.argtypes=[C.c_void_p,C.c_int,C.c_int,C.c_int,C.c_ulong]
    t.XTestFakeButtonEvent.argtypes=[C.c_void_p,C.c_uint,C.c_int,C.c_ulong]
    def click(pid,node):
        top=window_for_pid(x,display,pid,b'zkey native')
        x.XSetInputFocus(display,top,2,0)
        bounds=node.get_component_iface().get_extents(Atspi.CoordType.SCREEN)
        if bounds.width<=0 or bounds.height<=0:raise AssertionError('Fault recovery button not visible')
        t.XTestFakeMotionEvent(display,-1,bounds.x+bounds.width//2,bounds.y+bounds.height//2,0)
        t.XTestFakeButtonEvent(display,1,True,0);t.XTestFakeButtonEvent(display,1,False,0);x.XFlush(display);pump(.2)
    def screenshot(name):
        subprocess.run([sys.executable,str(ROOT/'native/tests/capture.py'),str(ROOT/f'.tmp/native-{name}.png')],check=True)
    screenshot('runtime-settings-error');click(dialog_pid,close)
    x.XSetInputFocus(display,xid,2,0);x.XFlush(display);pump(.15)
    # The engine is alive but must keep the keys literal while config is invalid.
    key('a',control=True);key('BackSpace');expect(text,'')
    for letter in 'aas':key(letter)
    expect(text,'aas')
    binary=Path(os.environ.get('ZKEY_NATIVE_BINARY',ROOT/'native/target/release/zkey-native'))
    env=dict(os.environ,GTK_IM_MODULE='gtk-im-context-simple');env.pop('NO_AT_BRIDGE',None)
    process=subprocess.Popen([str(binary),'--settings'],env=env)
    try:
        Atspi,app=editor_ui.connect(process.pid)
        deadline=time.monotonic()+5
        while time.monotonic()<deadline:
            nodes=list(editor_ui.walk(app))
            save=next((n for n in nodes if n.get_role()==Atspi.Role.PUSH_BUTTON and n.get_name()=='Lưu thiết lập'),None)
            close=next((n for n in nodes if n.get_role()==Atspi.Role.PUSH_BUTTON and n.get_name()=='Đóng'),None)
            experimental=next((n for n in nodes if n.get_role()==Atspi.Role.CHECK_BOX and 'sửa surrounding' in n.get_name()),None)
            if save and close and experimental:break
            pump(.03)
        else:raise AssertionError('Recovery settings controls missing')
        click(process.pid,experimental);click(process.pid,save)
        if not any((n.get_name() or '').startswith('Đã lưu.') for n in editor_ui.walk(app) if n.get_role()==Atspi.Role.LABEL):
            raise AssertionError('Actual settings repair was not saved')
        click(process.pid,close);process.wait(timeout=5)
        if process.returncode:raise AssertionError('Settings repair failed to exit')
    finally:
        if process.poll() is None:process.terminate();process.wait(timeout=5)
    x.XSetInputFocus(display,xid,2,0);x.XFlush(display);pump(.15)
    # Force a real context transition after the repair, then use real keys.
    if text.has_focus():key('Tab')
    key('Tab')
    if not text.has_focus():raise AssertionError('Could not refocus after settings repair')
    key('a',control=True);key('BackSpace');expect(text,'')
    for letter in 'aas':key(letter)
    expect(text,'ấ')
    if (session/'settings-invalid').exists():raise AssertionError('Recovered engine left the settings fault asserted')
    screenshot('runtime-settings-recovered')
    print('PASS native runtime config failure: visible warning + literal bypass -> settings UI repair -> actual Telex restored')
