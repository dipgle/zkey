"""Fault-only fixture. Corrupt config to exercise the real launcher warning;
repair ONLY by `zkey-native --set` (the real settings entry point), then type again.

The launcher's warning is a critical desktop notification. This fixture owns
org.freedesktop.Notifications on the launcher's PRIVATE session bus (the one its
children inherit), records the real Notify call, and checks it; the user's own
desktop bus is never involved.
"""
from pathlib import Path
import os
import subprocess
import sys
import time

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'native/tests'))
from notify_sink import Sink


def exercise(window, text, password, key, expect, pump, x, t, display, xid):
    config = Path(os.environ['ZKEY_NATIVE_CONFIG_PATH'])
    if not config.resolve().is_relative_to(ROOT / '.tmp'): raise RuntimeError('Fault fixture config outside scratch')
    session_bus = os.environ.get('DBUS_SESSION_BUS_ADDRESS', '')
    if not session_bus.startswith('unix:path=') or str(ROOT / '.tmp') not in session_bus:
        raise RuntimeError('Not on the launcher private session bus; refusing to claim a notification name')
    sink = Sink(session_bus)
    try:
        # EXCEPTION: inject malformed bytes solely to exercise a failure. The valid
        # replacement below is generated by the real settings command, never seeded.
        config.write_text('schema = broken\n')
        key('Tab')  # password -> normal field: real focus-in reload rejects config
        if not text.has_focus(): raise AssertionError('Fault fixture did not return to typing entry')
        session = Path(os.environ['ZKEY_NATIVE_SESSION_ROOT'])
        deadline = time.monotonic() + 8
        while time.monotonic() < deadline and not sink.calls: pump(.02)
        if not sink.calls: raise AssertionError('Alive-but-disabled native engine posted no supervisor warning')
        call = sink.calls[0]
        if 'Telex đã tắt' not in call['body'] or call['urgency'] != 2 or call['timeout'] != 0:
            raise AssertionError(f'Runtime failure warning is not a readable critical notification: {call}')
        # The engine is alive but must keep the keys literal while config is invalid.
        key('a', control=True); key('BackSpace'); expect(text, '')
        for letter in 'aas': key(letter)
        expect(text, 'aas')
        binary = Path(os.environ.get('ZKEY_NATIVE_BINARY', ROOT / 'native/target/release/zkey-native'))
        env = {k: v for k, v in os.environ.items() if k != 'IBUS_ADDRESS'}
        repaired = subprocess.run([str(binary), '--set', 'enabled=true', 'experimental_rewrite=true'], env=env,
                                  capture_output=True, text=True, timeout=30)
        if repaired.returncode != 0 or 'Đã lưu' not in repaired.stdout:
            raise AssertionError(f'Actual settings repair was not saved: {repaired.returncode} {repaired.stdout!r}')
        x.XSetInputFocus(display, xid, 2, 0); x.XFlush(display); pump(.15)
        # Force a real context transition after the repair, then use real keys.
        if text.has_focus(): key('Tab')
        key('Tab')
        if not text.has_focus(): raise AssertionError('Could not refocus after settings repair')
        key('a', control=True); key('BackSpace'); expect(text, '')
        for letter in 'aas': key(letter)
        expect(text, 'ấ')
        if (session / 'settings-invalid').exists(): raise AssertionError('Recovered engine left the settings fault asserted')
        if len(sink.calls) != 1: raise AssertionError(f'Warning repeated or extra notifications: {sink.calls}')
        subprocess.run([sys.executable, str(ROOT / 'native/tests/capture.py'),
                        str(ROOT / '.tmp/native-runtime-settings-recovered.png')], check=True)
    finally:
        sink.close()
    print('PASS native runtime config failure: critical notification + literal bypass -> settings --set repair -> actual Telex restored')
